import java.sql.Connection;
import java.sql.PreparedStatement;
import java.time.LocalDate;
import java.time.LocalTime;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Integration tests verifying live MySQL JDBC connectivity, floor-wise 20-seat provisioning,
 * maintenance status enforcement, and transactional booking read/write operations.
 */
public class FloorAndDatabaseTest {

    @Test
    @DisplayName("Verify live MySQL connection and 20 seats per seeded floor")
    void testMySqlConnectionAndSeededFloors() {
        assertTrue(DBConnection.getInstance().testConnection(),
                "MySQL JDBC connection must succeed with configured db.properties");

        FloorDAO floorDAO = new FloorDAOImpl();
        SeatDAO seatDAO = new SeatDAOImpl();

        List<Floor> floors = floorDAO.findAll(true);
        assertTrue(floors.size() >= 4, "At least 4 seeded floors should exist in MySQL");

        for (Floor f : floors) {
            List<Seat> floorSeats = seatDAO.findByFloorId(f.getFloorId());
            assertEquals(20, floorSeats.size(),
                    "Each floor must contain exactly 20 seats: " + f.getFloorName());
        }

        // Verify live MySQL login works with default evaluation credentials
        AuthService authService = new AuthService();
        User student = assertDoesNotThrow(() -> authService.login("student1", "password123"));
        assertTrue(student.isStudent());
        User admin = assertDoesNotThrow(() -> authService.login("admin", "password123"));
        assertTrue(admin.isAdmin());
        authService.logout();
    }

    @Test
    @DisplayName("Verify adding a new floor auto-generates 20 seats and cleans up")
    void testAddFloorAutoCreates20Seats() throws Exception {
        SeatService seatService = new SeatService();
        FloorDAO floorDAO = new FloorDAOImpl();

        // Clean up any leftover test floor #49 first
        floorDAO.findByFloorNumber(49).ifPresent(f -> deleteTestFloor(f.getFloorId()));

        Floor created = seatService.addFloor("Test Mezzanine — Section 49", 49, "Automated test floor", 1);
        assertTrue(created.getFloorId() > 0, "Generated floor_id must be positive");

        List<Seat> seats = seatService.getSeatsByFloor(created.getFloorId());
        assertEquals(20, seats.size(), "New floor must automatically receive 20 seats");
        assertEquals("S-01", seats.get(0).getSeatNumber());
        assertEquals("S-20", seats.get(19).getSeatNumber());

        // Duplicate floor number should be rejected
        assertThrows(InvalidBookingException.class, () ->
                seatService.addFloor("Duplicate Floor", 49, "Should fail", 1));

        // Cleanup test floor (ON DELETE CASCADE removes its 20 seats)
        deleteTestFloor(created.getFloorId());
    }

    @Test
    @DisplayName("Verify transactional booking, conflict prevention, and maintenance enforcement in MySQL")
    void testLiveBookingAndMaintenanceEnforcement() throws Exception {
        SeatService seatService = new SeatService();
        BookingService bookingService = new BookingService();
        BookingDAO bookingDAO = new BookingDAOImpl();

        List<Floor> floors = seatService.getAllActiveFloors();
        assertFalse(floors.isEmpty());

        // Pick Seat S-10 on Floor 0 (Ground Floor)
        Seat targetSeat = seatService.getSeatsByFloor(floors.get(0).getFloorId()).stream()
                .filter(s -> "S-10".equals(s.getSeatNumber()))
                .findFirst()
                .orElseThrow();

        LocalDate testDate = LocalDate.now().plusDays(5);
        LocalTime start = LocalTime.of(14, 0);
        LocalTime end = LocalTime.of(16, 0);

        // 1. Place booking in MySQL
        Booking created = bookingService.createBooking(2, targetSeat.getId(), testDate, start, end);
        assertTrue(created.getId() > 0, "Booking ID must be generated by MySQL");

        // 2. Conflict check must block overlapping booking on same seat & slot
        assertThrows(BookingConflictException.class, () ->
                bookingService.createBooking(3, targetSeat.getId(), testDate, LocalTime.of(15, 0), LocalTime.of(17, 0)));

        // 3. Cancel & verify
        assertTrue(bookingService.cancelBooking(created.getId(), 2));
        deleteTestBooking(created.getId());

        // 4. Maintenance enforcement
        assertTrue(seatService.updateSeatStatus(targetSeat.getId(), SeatStatus.MAINTENANCE, 1));
        assertThrows(SeatUnavailableException.class, () ->
                bookingService.createBooking(2, targetSeat.getId(), testDate, start, end));

        // Restore seat status back to AVAILABLE
        assertTrue(seatService.updateSeatStatus(targetSeat.getId(), SeatStatus.AVAILABLE, 1));
        assertNotNull(bookingDAO.findAllRecent(5));
    }

    private void deleteTestFloor(int floorId) {
        try (Connection conn = DBConnection.getInstance().getConnection();
             PreparedStatement ps = conn.prepareStatement("DELETE FROM floors WHERE floor_id = ?")) {
            ps.setInt(1, floorId);
            ps.executeUpdate();
        } catch (Exception ignored) {}
    }

    private void deleteTestBooking(int bookingId) {
        try (Connection conn = DBConnection.getInstance().getConnection();
             PreparedStatement ps = conn.prepareStatement("DELETE FROM bookings WHERE booking_id = ?")) {
            ps.setInt(1, bookingId);
            ps.executeUpdate();
        } catch (Exception ignored) {}
    }
}
